-- ============================================
-- Measurements table
-- ============================================
CREATE TABLE IF NOT EXISTS measurements (
    id            BIGSERIAL PRIMARY KEY,
    project_id    BIGINT       NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    chunk_id      BIGINT,                          -- referência lógica ao chunk (sem FK rígida)
    name          VARCHAR(255) NOT NULL,
    type          VARCHAR(50)  NOT NULL,           -- distance | area | volume | height
    value         DOUBLE PRECISION NOT NULL,
    unit          VARCHAR(20)  NOT NULL,           -- m | m² | m³
    data_source   VARCHAR(50)  NOT NULL,           -- orthophoto | dsm | dtm
    coordinates_json TEXT,                         -- JSON: [[lat,lng],[lat,lng],...]
    created_at    TIMESTAMP    NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMP    NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_measurement_project_id  ON measurements(project_id);
CREATE INDEX IF NOT EXISTS idx_measurement_chunk_id    ON measurements(chunk_id);
CREATE INDEX IF NOT EXISTS idx_measurement_created_at  ON measurements(created_at);

