-- ============================================
-- FuncaoODM Database Initialization Script
-- ============================================

-- Create extension for UUID generation (optional)
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- ============================================
-- USERS TABLE
-- This table is managed by JPA/Hibernate, but we ensure it exists
-- ============================================
CREATE TABLE IF NOT EXISTS users (
    id BIGSERIAL PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    tenant_id VARCHAR(64),  -- tenant da IAM (UUID em texto); preenchido via JIT provisioning
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- ============================================
-- PROJECTS TABLE
-- ============================================
CREATE TABLE IF NOT EXISTS projects (
    id BIGSERIAL PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    description VARCHAR(1000),
    status VARCHAR(50) DEFAULT 'PENDING',
    tenant_id VARCHAR(64),  -- fronteira de tenant (UUID da IAM); todas as queries filtram por ele
    empreendimento_id BIGINT,  -- vínculo cross-DB com o ERP (sem FK); nullable
    obra_id BIGINT,            -- vínculo cross-DB com o ERP (sem FK); nullable
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE
);

-- ============================================
-- PROCESSING TASKS TABLE
-- ============================================
CREATE TABLE IF NOT EXISTS processing_tasks (
    id BIGSERIAL PRIMARY KEY,
    nodeodm_task_id VARCHAR(255),  -- Can be NULL initially, filled after NodeODM task creation
    name VARCHAR(255),
    status VARCHAR(50) DEFAULT 'PENDING' NOT NULL,
    progress INTEGER DEFAULT 0 NOT NULL,
    status_message VARCHAR(500),
    options TEXT,
    outputs TEXT,
    error_message TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    started_at TIMESTAMP,
    completed_at TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE
);

-- ============================================
-- Create indexes for better performance
-- ============================================
CREATE INDEX IF NOT EXISTS idx_users_username ON users(username);
CREATE INDEX IF NOT EXISTS idx_users_email ON users(email);
CREATE INDEX IF NOT EXISTS idx_projects_owner_id ON projects(owner_id);
CREATE INDEX IF NOT EXISTS idx_projects_status ON projects(status);
CREATE INDEX IF NOT EXISTS idx_projects_tenant_id ON projects(tenant_id);
CREATE INDEX IF NOT EXISTS idx_users_tenant_id ON users(tenant_id);
CREATE INDEX IF NOT EXISTS idx_projects_empreendimento_id ON projects(tenant_id, empreendimento_id);
CREATE INDEX IF NOT EXISTS idx_projects_obra_id ON projects(tenant_id, obra_id);
CREATE INDEX IF NOT EXISTS idx_tasks_project_id ON processing_tasks(project_id);
CREATE INDEX IF NOT EXISTS idx_tasks_status ON processing_tasks(status);

